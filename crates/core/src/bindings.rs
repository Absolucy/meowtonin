use std::fmt::Write as _;

inventory::collect!(ExportedFn);

pub struct ExportedParam {
	pub name: &'static str,
	pub docs: &'static [&'static str],
}

/// Submitted by `#[byond_fn]` for every function it wraps.
pub struct ExportedFn {
	pub symbol: &'static str,
	pub dm_name: &'static str,
	pub docs: &'static [&'static str],
	pub params: &'static [ExportedParam],
	pub signature: &'static str,
	pub variadic: bool,
	/// Index of the first parameter of the trailing run of `Option`s.
	pub optional_from: Option<usize>,
}

/// Generates a DM file with one documented `#define` per `#[byond_fn]`, each
/// calling the function through a `load_ext` handle it caches in a global.
///
/// `lib_name` is the library's file name without the extension. Call this from
/// a test and write the result where your DM code includes it:
///
/// ```no_run
/// #[test]
/// fn generate_dm() {
///     std::fs::write("mylib.dm", meowtonin::bindings::generate_dm("mylib")).unwrap();
/// }
/// ```
///
/// The wrappers are function-like defines named after the Rust function, so
/// `add(1, 2)` anywhere else in the codebase gets rewritten too. Give exported
/// functions a library prefix, or use `#[byond_fn(name = "mylib_add")]`.
///
/// Define `MYLIB` before including the file to change where the library is
/// loaded from. The default drops the `lib` prefix on Windows only, which is
/// not checked against how BYOND resolves names on Linux.
pub fn generate_dm(lib_name: &str) -> String {
	let lib_ident = lib_name
		.chars()
		.map(|c| {
			if c.is_ascii_alphanumeric() {
				c.to_ascii_lowercase()
			} else {
				'_'
			}
		})
		.collect::<String>();
	let lib_define = lib_ident.to_ascii_uppercase();

	let mut funcs = inventory::iter::<ExportedFn>
		.into_iter()
		.collect::<Vec<_>>();
	funcs.sort_by_key(|func| func.dm_name);

	let mut out = format!(
		"// Generated by meowtonin. Do not edit by hand.\n// Define {lib_define} before including \
		 this file to change where the library is loaded from.\n\n#ifndef {lib_define}\n#define \
		 {lib_define} (world.system_type == MS_WINDOWS ? \"{lib_name}\" : \
		 \"lib{lib_name}\")\n#endif\n"
	);
	for func in funcs {
		out.push('\n');
		write_wrapper(&mut out, func, &lib_ident, &lib_define);
	}
	out
}

fn doc_comment(out: &mut String, lines: &[String]) {
	for line in lines {
		if line.is_empty() {
			out.push_str("///\n");
		} else {
			let _ = writeln!(out, "/// {line}");
		}
	}
}

fn write_wrapper(out: &mut String, func: &ExportedFn, lib_ident: &str, lib_define: &str) {
	let first_optional = func.optional_from.unwrap_or(func.params.len());
	let has_arg_docs =
		func.optional_from.is_some() || func.params.iter().any(|param| !param.docs.is_empty());

	let mut docs = func
		.docs
		.iter()
		.map(|line| (*line).to_owned())
		.collect::<Vec<_>>();
	if has_arg_docs {
		if !docs.is_empty() {
			docs.push(String::new());
		}
		docs.push("Arguments:".to_owned());
		for (idx, param) in func.params.iter().enumerate() {
			let mut line = format!("* {}", param.name);
			let optional = idx >= first_optional;
			if optional || !param.docs.is_empty() {
				line.push_str(" -");
			}
			if optional {
				line.push_str(" (optional)");
			}
			for doc in param.docs {
				let _ = write!(line, " {doc}");
			}
			docs.push(line);
		}
	}
	if !docs.is_empty() {
		docs.push(String::new());
	}
	docs.push(format!("Rust: `{}`", func.signature));
	doc_comment(out, &docs);

	let names = func
		.params
		.iter()
		.map(|param| param.name)
		.collect::<Vec<_>>();
	let (macro_params, call_args) = if func.variadic {
		let name = names.first().copied().unwrap_or("args");
		(format!("{name}..."), name.to_owned())
	} else if names.is_empty() {
		("...".to_owned(), String::new())
	} else if first_optional < names.len() {
		// a define cannot have defaults, so the optional tail is one variadic
		let mut macro_params = names[..first_optional].join(", ");
		if first_optional > 0 {
			macro_params.push_str(", ");
		}
		let _ = write!(macro_params, "{}...", names[first_optional]);
		let call_args = names[..=first_optional].join(", ");
		(macro_params, call_args)
	} else {
		(names.join(", "), names.join(", "))
	};

	let handle = format!("__{lib_ident}_{}", func.symbol);
	let _ = writeln!(
		out,
		"#define {}({macro_params}) call_ext({handle} ||= load_ext({lib_define}, \
		 \"byond:{}\"))({call_args})",
		func.dm_name, func.symbol
	);
	let _ = writeln!(out, "var/static/{handle}");
}
